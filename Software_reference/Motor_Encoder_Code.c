/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_USART2_UART_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */

  HAL_TIM_Encoder_Start(&htim3, TIM_CHANNEL_ALL);

  uint16_t previous_count = __HAL_TIM_GET_COUNTER(&htim3);
  int32_t total_count = 0;
  uint8_t first_reading = 1;

  // Kalman_Init(&current_kf, 0.0f, 0.001f, 0.05f);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  while (1)
  {
    /* USER CODE END WHILE */
	  while (1)
	  {
	      uint16_t current_count;
	      int16_t delta_count;

	      float rpm;
	      float angle;

	      char msg[120];

	      current_count = __HAL_TIM_GET_COUNTER(&htim3);

	      if (first_reading)
	      {
	          previous_count = current_count;
	          total_count = 0;
	          first_reading = 0;

	          rpm = 0.0f;
	          angle = 0.0f;
	      }
	      else
	      {
	          // Calculate encoder count change
	          delta_count = (int16_t)(current_count - previous_count);

	          total_count += delta_count;

	          previous_count = current_count;

	          // Provisional gearbox output resolution
	          const float counts_per_output_rev = 2786.0f;

	          // Reverse RPM sign to display positive speed
	          rpm = -((float)delta_count
	                  / counts_per_output_rev) * 600.0f;

	          // Reverse angle direction and wrap between 0 and 360 degrees
	          angle = fmodf(
	              -((float)total_count * 360.0f)
	              / counts_per_output_rev,
	              360.0f
	          );

	          if (angle < 0.0f)
	          {
	              angle += 360.0f;
	          }
	      }

	      snprintf(msg, sizeof(msg),
	               "Count=%ld | RPM=%.2f | Angle=%.2f\r\n",
	               (long)total_count,
	               rpm,
	               angle);

	      HAL_UART_Transmit(&huart2,
	                        (uint8_t*)msg,
	                        strlen(msg),
	                        HAL_MAX_DELAY);

	      HAL_Delay(100);
	  }
    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

